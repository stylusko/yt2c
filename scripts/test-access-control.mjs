import assert from 'node:assert/strict';
import {signSession,readSession,cookieToken,sessionCookie,accessState,sameOrigin,blockedWebPath,SESSION_SECONDS,SESSION_COOKIE,signAccessRecord,readAccessRecord} from '../lib/access-control.mjs';
const secret='a'.repeat(64),user={uid:'existing-uid',email:'owner@example.test'},now=1_900_000_000_000;
const token=signSession(user,secret,now);
assert.equal(readSession(token,secret,now).uid,user.uid);
assert.equal(readSession(token,secret,now+SESSION_SECONDS*1000),null);
for(const bad of [token+'x',token.replace('ey','aX'),token+'.more','invalid','',undefined]) assert.equal(readSession(bad,secret,now),null);
assert.equal(readSession(token,'other-secret'.repeat(5),now),null);
assert.equal(readSession(token,undefined,now),null);
assert.equal(cookieToken('other=1; youmeca_legacy_session='+token+'; third=2'),token);
assert.equal(SESSION_COOKIE,'__session');
assert.equal(cookieToken('__session='+token+'; youmeca_legacy_session=old'),token);
assert.equal(sameOrigin('https://youmeca-service.web.app','https://youmeca.me,https://youmeca-service.web.app'),true);
assert.equal(sameOrigin('https://youmeca-service.web.app.evil.example','https://youmeca.me,https://youmeca-service.web.app'),false);
assert.match(sessionCookie(token),/HttpOnly; SameSite=Lax; Max-Age=604800; Secure/);
assert.match(sessionCookie(''),/Max-Age=0/);
assert.deepEqual(accessState(null,{status:'approved'},'admin'),{authenticated:false,approved:false,admin:false});
assert.equal(accessState(user,null,'admin').approved,false);
assert.equal(accessState(user,{status:'pending'},'admin').approved,false);
assert.equal(accessState(user,{status:'approved'},'admin').approved,true);
assert.equal(accessState(user,{status:'revoked'},'admin').approved,false);
assert.equal(accessState(user,null,user.uid).admin,true);
assert.equal(accessState({...user,uid:'imposter'},null,user.uid).admin,false,'same email never grants admin rights');
assert.equal(sameOrigin('https://youmeca.me','https://youmeca.me'),true);
for(const origin of ['https://youmeca.me.attacker.test','null','http://youmeca.me',undefined]) assert.equal(sameOrigin(origin,'https://youmeca.me'),false);
for(const path of ['/bmonly','/bmonly/edit','/%62monly','/s/abc/bmonly','/bmonly%2Fedit','/bmonly\\edit','/BMOnly/Edit','/S/AbC/BMONLY']) assert.equal(blockedWebPath(path),true);
assert.equal(blockedWebPath('/'),false);
console.log('Session expiry, tampering, UID-only admin, approval/revocation, origin and closed route checks passed.');

const record={uid:user.uid,email:user.email,status:'approved'},signed=signAccessRecord(record,secret);
assert.deepEqual(readAccessRecord(signed,secret),record);
assert.equal(readAccessRecord(JSON.stringify(record),secret),null);
const altered=JSON.parse(signed);altered.data=Buffer.from(JSON.stringify({...record,status:'revoked'})).toString('base64url');
assert.equal(readAccessRecord(JSON.stringify(altered),secret),null);
assert.equal(readAccessRecord(signed,'wrong'.repeat(20)),null);
assert.equal(readSession(JSON.parse(signed).data+'.'+JSON.parse(signed).signature,secret,now),null);
console.log('Tampered approval storage cannot grant access or forge a session.');
